/** 38 → «3 года 2 мес.»; 12 → «1 год»; 5 → «5 мес.» */
export function yearsMonthsText(total: number): string {
  const y = Math.floor(total / 12)
  const m = total % 12
  const yWord = y % 10 === 1 && y % 100 !== 11 ? 'год' : y % 10 >= 2 && y % 10 <= 4 && (y % 100 < 12 || y % 100 > 14) ? 'года' : 'лет'
  if (!y) return `${m} мес.`
  return m ? `${y} ${yWord} ${m} мес.` : `${y} ${yWord}`
}

